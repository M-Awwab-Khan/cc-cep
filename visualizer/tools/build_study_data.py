"""Regenerate dist/study-data.mjs from the frozen curated study summary.

Usage (from the repository root): python visualizer/tools/build_study_data.py
Reads results/curated/final-study-summary.json; never edits measurement data.
"""
import json, pathlib
root = pathlib.Path(__file__).resolve().parents[2]
src = root / "results/curated/final-study-summary.json"
d = json.loads(src.read_text(encoding="utf-8"))
r = lambda x, n=2: round(float(x), n)
latency = [p for p in d["paired"] if p["slo"] == "latency" and p["metric"] in ("guard_overshoot", "exposure")]
out = {
    "source": "results/curated/final-study-summary.json",
    "study": d["study"],
    "selectedRuns": d["selected_runs"],
    "retainedAttempts": d["retained_attempts"],
    "failedAttempts": d["failed_attempts"],
    "maxFullAllocationOvershoot": d["full_allocation_overshoot_max"],
    "cleanNoFaultControls": d["no_fault_controls_zero_bad_and_debit"],
    "exposureUnit": d["exposure_unit"],
    "limitations": d["limitations"],
    "means": [
        {k: (r(v) if isinstance(v, float) else v) for k, v in m.items()}
        for m in d["core_latency_slo_means"]
    ],
    "paired": [
        {
            "family": p["family"], "rps": int(p["rps"]), "metric": p["metric"],
            "comparator": p["comparator"], "n": int(p["n"]), "complete": p["complete"] == "True",
            "mean": r(p["mean_difference"]), "low": r(p["ci_low"]), "high": r(p["ci_high"]),
        }
        for p in latency
    ],
}
dest = root / "visualizer/dist/study-data.mjs"
dest.write_text(
    "// GENERATED by tools/build_study_data.py from " + out["source"] + ". Do not edit by hand.\n"
    "export const study=" + json.dumps(out, separators=(",", ":")) + ";\n",
    encoding="utf-8", newline="\n")
print("wrote", dest, len(out["means"]), "means,", len(out["paired"]), "paired rows")
